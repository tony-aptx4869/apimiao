def get_lang() -> str:
    lang = request.cookies.get("apimiao_lang", DEFAULT_LANG)
    return lang if lang in LANGS else DEFAULT_LANG


def t(key: str, **kwargs) -> str:
    s = T.get(get_lang(), T[DEFAULT_LANG]).get(key, T[DEFAULT_LANG].get(key, key))
    return s.format(**kwargs) if kwargs else s


def init_app(app):
    @app.before_request
    def _set_lang():
        g.lang = get_lang()
